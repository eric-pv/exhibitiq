"""Snapshot verification, byte-exact regeneration check, and verified backup / restore of data packages (D4-03).

Three questions, each answered with evidence and never by assumption:

1. **Are the raw snapshots still there and unchanged?** ``verify_snapshots`` checks every source of a package whose
   snapshot is stored in Git (``snapshot.storage == "git"``): the file at ``snapshot.locator`` (relative to the
   repository root) must exist and hash to ``content_sha256``. Sources that were deliberately not stored
   (``not_stored``) or are stored elsewhere are listed, not reported as verified.
2. **Can the package be regenerated byte for byte from its records?** ``check_regenerable`` writes the package's
   records again with ``etl.package.write_package`` into a temporary directory and compares every file and the
   ``content_hash``. A difference means the package on disk is not what the code would produce from its own records.
3. **Can it be backed up and restored without loss?** ``create_backup`` writes one deterministic ``.tar.gz`` holding the
   packages and the Git-stored snapshots they cite, with ``backup-manifest.json`` listing every file's sha256 and every
   package's ``content_hash``. ``verify_backup`` checks a bundle without extracting it; ``restore_backup`` extracts into
   an empty directory (refusing unsafe paths, links and unlisted members), then re-validates every package (R1-R11),
   compares ``content_hash`` and re-checks the snapshots.

Where a backup is kept (Release, external storage, ...) is not decided here; this module only makes and checks the file.

Command line (exit 0 = everything verified, 1 = problems found and listed, 2 = bad input)::

    python -m etl.integrity snapshots [--repo-root .] PACKAGE_DIR...
    python -m etl.integrity regen PACKAGE_DIR...
    python -m etl.integrity backup --out BUNDLE.tar.gz [--repo-root .] [--created-at 2026-11-09T00:00:00Z] PACKAGE_DIR...
    python -m etl.integrity verify-backup BUNDLE.tar.gz
    python -m etl.integrity restore BUNDLE.tar.gz TARGET_DIR
"""
from __future__ import annotations

import argparse
import gzip
import io
import json
import sys
import tarfile
import tempfile
from collections.abc import Iterable, Sequence
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath
from typing import Any

from etl.hashing import sha256_of_bytes
from etl.package import COMPUTED_MANIFEST_FIELDS, DATA_FILES, MANIFEST_FILE, PackageError, read_package, write_package
from etl.validate import validate_package

BACKUP_VERSION = 1
BACKUP_MANIFEST = "backup-manifest.json"


class IntegrityError(ValueError):
    """The request cannot be carried out (bad input or an unsafe bundle); nothing was written or extracted."""


# ------------------------------------------------------------------------------------------ snapshots


def verify_snapshots(package_dir: str | Path, repo_root: str | Path) -> dict[str, Any]:
    """Check the Git-stored snapshots cited by a package. ``problems`` empty = every stored snapshot verified."""
    package = read_package(package_dir)
    root = Path(repo_root)
    verified: list[str] = []
    not_stored: list[str] = []
    elsewhere: list[dict[str, str]] = []
    problems: list[str] = []
    for source in package.records["sources"]:
        sid, snapshot = source["source_id"], source.get("snapshot") or {}
        storage = snapshot.get("storage")
        if storage == "not_stored":
            not_stored.append(sid)
            continue
        if storage != "git":
            elsewhere.append({"source_id": sid, "storage": str(storage)})
            continue
        locator = snapshot.get("locator")
        try:
            relative = _safe_relative(locator)
        except IntegrityError as exc:
            problems.append(f"{sid}: {exc}")
            continue
        file = root / relative
        if not file.is_file():
            problems.append(f"{sid}: {locator} does not exist")
        elif sha256_of_bytes(file.read_bytes()) != source["content_sha256"]:
            problems.append(f"{sid}: {locator} does not match content_sha256")
        else:
            verified.append(sid)
    return {"dataset_id": package.manifest["dataset_id"], "verified": verified, "not_stored": not_stored, "stored_elsewhere": elsewhere, "problems": problems}


# --------------------------------------------------------------------------------------- regeneration


def check_regenerable(package_dir: str | Path) -> list[str]:
    """Differences between the package on disk and the package ``write_package`` produces from its records (empty = identical)."""
    directory = Path(package_dir)
    package = read_package(directory)
    manifest = {k: v for k, v in package.manifest.items() if k not in COMPUTED_MANIFEST_FIELDS}
    problems: list[str] = []
    with tempfile.TemporaryDirectory(prefix="exhibitiq-regen-") as temp:
        target = Path(temp) / directory.name
        try:
            rebuilt = write_package(target, exhibition=package.exhibition, edition=package.edition, records=package.records, manifest=manifest)
        except PackageError as exc:
            return [f"cannot be written again from its records: {exc}"]
        for name in (*DATA_FILES, MANIFEST_FILE):
            if (directory / name).read_bytes() != (target / name).read_bytes():
                problems.append(f"{name}: bytes differ from the regenerated file")
        if rebuilt["content_hash"] != package.manifest["content_hash"]:
            problems.append(f"content_hash {package.manifest['content_hash']} differs from the regenerated {rebuilt['content_hash']}")
    return problems


# ------------------------------------------------------------------------------------------- backup


def _safe_relative(name: Any) -> PurePosixPath:
    if not isinstance(name, str) or not name or "\\" in name or "\x00" in name:
        raise IntegrityError(f"unsafe path {name!r}")
    path = PurePosixPath(name)
    if path.is_absolute() or any(part in {"", ".", ".."} for part in path.parts) or name != path.as_posix():
        raise IntegrityError(f"unsafe path {name!r}")
    return path


def _relative_to_root(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        raise IntegrityError(f"{path} is not inside the repository root {root}") from None


def _tar_member(tar: tarfile.TarFile, name: str, data: bytes) -> None:
    info = tarfile.TarInfo(name)
    info.size, info.mtime, info.mode, info.uid, info.gid, info.uname, info.gname = len(data), 0, 0o644, 0, 0, "", ""
    tar.addfile(info, io.BytesIO(data))


def create_backup(package_dirs: Iterable[str | Path], out_path: str | Path, *, repo_root: str | Path, created_at: datetime) -> dict[str, Any]:
    """Write a verified, byte-reproducible backup bundle. Refuses packages that fail validation or cite missing snapshots."""
    root = Path(repo_root)
    out = Path(out_path)
    if out.exists():
        raise IntegrityError(f"{out} already exists; a backup is never overwritten")
    dirs = sorted({Path(d) for d in package_dirs}, key=lambda p: _relative_to_root(p, root))
    if not dirs:
        raise IntegrityError("no packages given")
    files: dict[str, bytes] = {}
    packages: list[dict[str, Any]] = []
    for directory in dirs:
        report = validate_package(directory)
        if not report.ok:
            raise IntegrityError(f"{directory} fails validation ({len(report.findings)} finding(s), first: {report.findings[0]}); fix it before backing it up")
        snapshots = verify_snapshots(directory, root)
        if snapshots["problems"]:
            raise IntegrityError(f"{directory}: snapshots cannot be backed up: {'; '.join(snapshots['problems'])}")
        manifest = read_package(directory).manifest
        prefix = _relative_to_root(directory, root)
        for name in (*DATA_FILES, MANIFEST_FILE):
            files[f"{prefix}/{name}"] = (directory / name).read_bytes()
        for source in read_package(directory).records["sources"]:
            if source["source_id"] in snapshots["verified"]:
                locator = source["snapshot"]["locator"]
                files[locator] = (root / locator).read_bytes()
        packages.append({"dataset_id": manifest["dataset_id"], "path": prefix, "content_hash": manifest["content_hash"], "data_origin": manifest["data_origin"],
                         "snapshots_verified": len(snapshots["verified"]), "snapshots_not_stored": snapshots["not_stored"]})
    listing = {
        "version": BACKUP_VERSION, "created_at": created_at.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "packages": packages,
        "files": [{"path": name, "sha256": sha256_of_bytes(files[name]), "bytes": len(files[name])} for name in sorted(files, key=str.encode)],
    }
    buffer = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buffer, mtime=0) as gz, tarfile.open(fileobj=gz, mode="w", format=tarfile.GNU_FORMAT) as tar:
        _tar_member(tar, BACKUP_MANIFEST, (json.dumps(listing, ensure_ascii=False, sort_keys=True, indent=1) + "\n").encode("utf-8"))
        for name in sorted(files, key=str.encode):
            _tar_member(tar, name, files[name])
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "xb") as stream:
        stream.write(buffer.getvalue())
    return {"bundle": out.as_posix(), "sha256": sha256_of_bytes(buffer.getvalue()), "packages": len(packages), "files": len(files)}


def _read_bundle(bundle: str | Path) -> tuple[dict[str, Any], dict[str, bytes], list[str]]:
    """The listing, the member bytes and the problems found. Raises IntegrityError if the bundle cannot be read at all."""
    problems: list[str] = []
    members: dict[str, bytes] = {}
    try:
        with tarfile.open(bundle, mode="r:gz") as tar:
            for info in tar.getmembers():
                try:
                    _safe_relative(info.name)
                except IntegrityError as exc:
                    problems.append(f"member {exc}")
                    continue
                if not info.isfile():
                    problems.append(f"member {info.name} is not a regular file")
                    continue
                if info.name in members:
                    problems.append(f"member {info.name} appears twice")
                    continue
                members[info.name] = tar.extractfile(info).read()
    except (OSError, tarfile.TarError, EOFError) as exc:
        raise IntegrityError(f"{bundle} cannot be read as a backup bundle: {exc}") from None
    raw = members.pop(BACKUP_MANIFEST, None)
    if raw is None:
        raise IntegrityError(f"{bundle} has no {BACKUP_MANIFEST}")
    try:
        listing = json.loads(raw.decode("utf-8"))
        listed = {f["path"]: f for f in listing["files"]}
        packages = listing["packages"]
        if listing.get("version") != BACKUP_VERSION or not isinstance(packages, list):
            raise ValueError("unsupported version")
    except (ValueError, KeyError, TypeError, AttributeError) as exc:
        raise IntegrityError(f"{BACKUP_MANIFEST} is not a version {BACKUP_VERSION} backup listing: {exc}") from None
    for name in sorted(set(members) - set(listed)):
        problems.append(f"member {name} is not listed in {BACKUP_MANIFEST}")
    for name, entry in sorted(listed.items()):
        data = members.get(name)
        if data is None:
            problems.append(f"{name} is listed but missing from the bundle")
        elif sha256_of_bytes(data) != entry.get("sha256") or len(data) != entry.get("bytes"):
            problems.append(f"{name} does not match its listed sha256/bytes")
    return listing, members, problems


def verify_backup(bundle: str | Path) -> list[str]:
    """Problems of a bundle, checked without extracting it (empty = every member present and unchanged)."""
    return _read_bundle(bundle)[2]


def restore_backup(bundle: str | Path, target: str | Path) -> dict[str, Any]:
    """Extract a verified bundle into an empty or new ``target`` and verify every restored package."""
    listing, members, problems = _read_bundle(bundle)
    if problems:
        raise IntegrityError(f"{bundle} does not verify; nothing restored: {'; '.join(problems)}")
    root = Path(target)
    if root.exists() and (not root.is_dir() or any(root.iterdir())):
        raise IntegrityError(f"{root} exists and is not an empty directory; a restore never overwrites")
    for name in sorted(members, key=str.encode):
        path = root / _safe_relative(name)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "xb") as stream:
            stream.write(members[name])
    results = []
    for entry in listing["packages"]:
        directory = root / _safe_relative(entry["path"])
        report = validate_package(directory)
        found: list[str] = [str(f) for f in report.findings]
        if report.ok:
            manifest = read_package(directory).manifest
            if manifest["content_hash"] != entry["content_hash"]:
                found.append(f"content_hash {manifest['content_hash']} differs from the backup listing {entry['content_hash']}")
            found.extend(verify_snapshots(directory, root)["problems"])
        results.append({"dataset_id": entry["dataset_id"], "path": entry["path"], "ok": not found, "problems": found})
    return {"target": root.as_posix(), "files": len(members), "packages": results, "ok": all(r["ok"] for r in results)}


# ---------------------------------------------------------------------------------------------- CLI


def _parse_time(text: str) -> datetime:
    try:
        moment = datetime.strptime(text, "%Y-%m-%dT%H:%M:%SZ")
    except ValueError:
        raise argparse.ArgumentTypeError("use the form 2026-11-09T00:00:00Z") from None
    return moment.replace(tzinfo=timezone.utc)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m etl.integrity", description="Snapshot, regeneration and backup checks for data packages.")
    sub = parser.add_subparsers(dest="command", required=True)
    snap = sub.add_parser("snapshots", help="verify the Git-stored snapshots cited by packages")
    snap.add_argument("packages", nargs="+")
    snap.add_argument("--repo-root", default=".")
    regen = sub.add_parser("regen", help="check that packages are regenerated byte for byte from their records")
    regen.add_argument("packages", nargs="+")
    backup = sub.add_parser("backup", help="write a verified backup bundle")
    backup.add_argument("packages", nargs="+")
    backup.add_argument("--out", required=True)
    backup.add_argument("--repo-root", default=".")
    backup.add_argument("--created-at", type=_parse_time, default=None)
    check = sub.add_parser("verify-backup", help="verify a bundle without extracting it")
    check.add_argument("bundle")
    restore = sub.add_parser("restore", help="restore a bundle into an empty directory and verify it")
    restore.add_argument("bundle")
    restore.add_argument("target")
    args = parser.parse_args(argv)
    try:
        if args.command == "snapshots":
            out: Any = [verify_snapshots(p, args.repo_root) for p in args.packages]
            ok = all(not r["problems"] for r in out)
        elif args.command == "regen":
            out = [{"package": p, "problems": check_regenerable(p)} for p in args.packages]
            ok = all(not r["problems"] for r in out)
        elif args.command == "backup":
            out = create_backup(args.packages, args.out, repo_root=args.repo_root, created_at=args.created_at or datetime.now(timezone.utc))
            ok = True
        elif args.command == "verify-backup":
            out = {"bundle": args.bundle, "problems": verify_backup(args.bundle)}
            ok = not out["problems"]
        else:
            out = restore_backup(args.bundle, args.target)
            ok = out["ok"]
    except (IntegrityError, PackageError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(json.dumps(out, ensure_ascii=False, sort_keys=True, indent=1) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
